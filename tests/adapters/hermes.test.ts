// Compiles an emitted __init__.py with `python3 -m py_compile` -- proves the
// generated Python is at least syntactically valid, not just string-matched.
function pyCompile(source: string): { status: number | null } {
  const dir = mkdtempSync(join(tmpdir(), 'eh-hermes-pyc-'))
  const filePath = join(dir, '__init__.py')
  writeFileSync(filePath, source)
  try {
    execFileSync('python3', ['-m', 'py_compile', filePath], { stdio: 'pipe' })
    return { status: 0 }
  } catch (error) {
    return { status: (error as { status: number | null }).status }
  }
}

